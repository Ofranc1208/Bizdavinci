// Generate route/profession inventory from live application data.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { professions, professionPath, groups } from '../professions.js';
import { routes } from '../data.js';

const familyLabel = {
  dental: 'Dental',
  spa: 'Spa',
  home: 'Home services',
  health: 'Healthcare',
  professional: 'Professional'
};

export function inventoryMarkdown() {
  const shared = Object.entries(routes).filter(([route]) => !route.startsWith('/industries/'));
  const rows = professions.map(p => `| \`${professionPath(p.slug)}\` | ${p.name} | ${familyLabel[p.family] || p.family} | ${p.group} |`);
  return [
    `<!-- generated by frontend/scripts/inventory.mjs — do not hand-edit counts -->`,
    ``,
    `Registered routes: **${Object.keys(routes).length}** (${shared.length} shared + ${professions.length} profession).`,
    `Professions: **${professions.length}**. Browsing categories: **${groups.length}**.`,
    ``,
    `| Route | Profession | Design family | Category |`,
    `|---|---|---|---|`,
    ...rows,
    ``
  ].join('\n');
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../docs/audits/biz-da-vinci-remediation/ROUTE_INVENTORY.md');
  writeFileSync(out, inventoryMarkdown());
  console.log(`Wrote ${out}`);
}
